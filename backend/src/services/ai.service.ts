  'Statutory Advisory Notice: This analysis is generated by an automated AI assistant based strictly on historical farm records. It does not provide chemical prescriptions, pesticide/fertilizer dosage recommendations, or definitive disease diagnoses. Always consult a certified Agricultural Extension Officer before taking agronomic action.';

